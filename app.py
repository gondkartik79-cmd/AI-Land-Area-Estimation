from flask import Flask, render_template, request, send_from_directory, send_file
import os
import cv2
from io import BytesIO
from reportlab.pdfgen import canvas
from werkzeug.utils import secure_filename

app = Flask(__name__)

# Upload folder
UPLOAD_FOLDER = os.path.join(app.root_path, "uploads")
app.config["UPLOAD_FOLDER"] = UPLOAD_FOLDER

os.makedirs(UPLOAD_FOLDER, exist_ok=True)


# Home page
@app.route("/")
def home():
    return render_template("index.html")


# Display uploaded image
@app.route("/uploads/<filename>")
def uploaded_file(filename):
    return send_from_directory(
        app.config["UPLOAD_FOLDER"],
        filename
    )


# Calculate area
@app.route("/calculate", methods=["POST"])
def calculate():

    image = request.files.get("landImage")
    filename = ""

    # Upload image
    if image and image.filename:

        filename = secure_filename(image.filename)

        image_path = os.path.join(
            app.config["UPLOAD_FOLDER"],
            filename
        )

        image.save(image_path)

        # Open image using OpenCV
        img = cv2.imread(image_path)

        if img is not None:

            # Convert to grayscale
            gray = cv2.cvtColor(
                img,
                cv2.COLOR_BGR2GRAY
            )

            # Remove noise
            blur = cv2.GaussianBlur(
                gray,
                (5, 5),
                0
            )

            # Detect edges
            edges = cv2.Canny(
                blur,
                50,
                150
            )

            # Find contours
            contours, _ = cv2.findContours(
                edges,
                cv2.RETR_EXTERNAL,
                cv2.CHAIN_APPROX_SIMPLE
            )

            # Draw largest boundary
            if contours:

                largest_contour = max(
                    contours,
                    key=cv2.contourArea
                )

                cv2.drawContours(
                    img,
                    [largest_contour],
                    -1,
                    (0, 255, 0),
                    4
                )

                # Save boundary image
                boundary_filename = (
                    "boundary_" + filename
                )

                boundary_path = os.path.join(
                    app.config["UPLOAD_FOLDER"],
                    boundary_filename
                )

                cv2.imwrite(
                    boundary_path,
                    img
                )

    # Get length and width
    length = float(
        request.form["length"]
    )

    width = float(
        request.form["width"]
    )

    # Calculate area
    area = length * width

    # Convert units
    acre = area / 4046.856
    guntha = area / 101.171
    hectare = area / 10000

    return render_template(
        "index.html",
        length=length,
        width=width,
        area=area,
        acre=acre,
        guntha=guntha,
        hectare=hectare,
        filename=filename
    )


# Download PDF report
@app.route("/download_report")
def download_report():

    length = float(
        request.args.get("length", 0)
    )

    width = float(
        request.args.get("width", 0)
    )

    # Calculate values
    area = length * width
    acre = area / 4046.856
    guntha = area / 101.171
    hectare = area / 10000

    # Create PDF in memory
    pdf_buffer = BytesIO()

    pdf = canvas.Canvas(pdf_buffer)

    # Title
    pdf.setFont(
        "Helvetica-Bold",
        18
    )

    pdf.drawCentredString(
        300,
        780,
        "AI-Based Land Area Estimation System"
    )

    # Line
    pdf.line(
        50,
        755,
        550,
        755
    )

    # Heading
    pdf.setFont(
        "Helvetica-Bold",
        14
    )

    pdf.drawString(
        70,
        710,
        "Land Area Estimation Report"
    )

    # Details
    pdf.setFont(
        "Helvetica",
        12
    )

    pdf.drawString(
        80,
        660,
        f"Reference Length: {length:.2f} meters"
    )

    pdf.drawString(
        80,
        625,
        f"Width: {width:.2f} meters"
    )

    pdf.drawString(
        80,
        590,
        f"Square Meter: {area:.2f} m2"
    )

    pdf.drawString(
        80,
        555,
        f"Acre: {acre:.4f} acre"
    )

    pdf.drawString(
        80,
        520,
        f"Guntha: {guntha:.2f} guntha"
    )

    pdf.drawString(
        80,
        485,
        f"Hectare: {hectare:.4f} hectare"
    )

    # Footer
    pdf.setFont(
        "Helvetica-Oblique",
        10
    )

    pdf.drawString(
        80,
        430,
        "Generated by AI-Based Land Area Estimation System"
    )

    # Finish PDF
    pdf.save()

    pdf_buffer.seek(0)

    return send_file(
        pdf_buffer,
        as_attachment=True,
        download_name="land_area_report.pdf",
        mimetype="application/pdf"
    )


# Run Flask
if __name__ == "__main__":
    app.run(debug=False)